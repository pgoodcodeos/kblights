static int assignment_record_valid(const uint8_t r[4]) {
    if(!memcmp(r, (uint8_t[4]){0}, 4) || !memcmp(r, (uint8_t[4]){5, 3, 0, 0}, 4))
        return 1;

    if(r[0] == 2 && r[3] == 0 && (keyboardUsages[r[2]] || (r[2] == 0 && r[1] != 0)))
        return 1;

    if(r[0] == 1 && r[3] == 0) {
        if(r[1] == 1 && (r[2] == 1 || r[2] == 2 || r[2] == 4 || r[2] == 8 || r[2] == 16))
            return 1;

        if(r[1] == 3 && (r[2] == 1 || r[2] == 255))
            return 1;
    }

    for(unsigned i = 0; i < sizeof(mediaRecords) / sizeof(*mediaRecords); ++i)
        if(!memcmp(r, mediaRecords[i], 4))
            return 1;

    return 0;
}
